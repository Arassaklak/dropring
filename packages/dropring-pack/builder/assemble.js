'use strict';
// Assembles a "onedir" application for one target (DESIGN.md §4):
//   Windows  <Name>/<Name>.exe + <Name>/_internal/...
//   macOS    <Name>.app/Contents/{Info.plist, MacOS/<Name>, Resources/...}
// The app is built in a hidden staging folder next to the destination and moved into place
// only when complete, so a failed or cancelled build never leaves a half-written app.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { runtimeFilter } = require('./strip');
const { runtimeLayout } = require('./runtime');
const macos = require('./macos');
const { walk, isInside, sanitizeFileName, setTreeTimes, reproducibleDate, throwIfAborted } = require('./util');
const { hashTree, summarize } = require('./manifest');
const { zipDirectory } = require('./zip');

const PACK_VERSION = require('../package.json').version;
const BOOT_DIR = path.join(__dirname, '..', 'boot');
const MANIFEST_FILE = 'manifest.json';
const CONFIG_FILE = 'dropring-pack.cfg';

const TRANSLITERATE = { ı: 'i', İ: 'I', ß: 'ss', æ: 'ae', Æ: 'AE', ø: 'o', Ø: 'O', đ: 'd', Đ: 'D', ł: 'l', Ł: 'L', œ: 'oe', Œ: 'OE' };

/**
 * ASCII file name for the macOS main executable. codesign cannot seal a bundle whose
 * CFBundleExecutable has non-ASCII characters ("a sealed resource is missing or invalid"),
 * so "Ünïcode Äpp" runs as Contents/MacOS/Unicode App; bundle and display names stay Unicode.
 */
function asciiExecutableName(name) {
  const s = [...name.normalize('NFKD')].map((c) => TRANSLITERATE[c] ?? c).join('')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^\x20-\x7e]/g, '_')
    .replace(/[<>:"/\\|?*]/g, '_');
  const trimmed = s.replace(/^[\s._]+|[\s.]+$/g, '');
  return /[A-Za-z0-9]/.test(trimmed) ? trimmed : 'App';
}

/** Paths inside an app for a target. */
function layoutFor(target, fileName) {
  if (target.os === 'macos') {
    return { bundleName: `${fileName}.app`, base: 'Contents/Resources', executable: `Contents/MacOS/${asciiExecutableName(fileName)}` };
  }
  return { bundleName: fileName, base: '_internal', executable: `${fileName}.exe` };
}

const join = (root, rel) => path.join(root, ...rel.split('/'));

/** Permission bits for a path inside an app: folders, the launcher and native libraries are executable. */
function modeFor(rel, type, executable) {
  if (type === 'dir' || rel === executable || /\.(dylib|so|dll|pyd|exe)$/.test(rel)) return 0o755;
  return 0o644;
}

/** Copies the runtime with the strip filter; returns dropped bytes per reason. */
async function copyRuntime(src, dest, filter, warn) {
  const dropped = new Map();
  let kept = 0;
  for (const e of await walk(src)) {
    const reason = filter(e.rel);
    if (reason) {
      if (e.type !== 'dir') dropped.set(reason, (dropped.get(reason) || 0) + e.stat.size);
      continue;
    }
    if (e.type === 'dir') continue; // created on demand, so fully stripped folders disappear
    const target = join(dest, e.rel);
    await fs.promises.mkdir(path.dirname(target), { recursive: true });
    if (e.type === 'symlink') {
      const link = await fs.promises.readlink(e.abs);
      const resolved = path.resolve(path.dirname(e.abs), link);
      if (!isInside(src, resolved) || path.isAbsolute(link)) throw new Error(`runtime contains a link leaving the runtime: ${e.rel} -> ${link}`);
      try {
        await fs.promises.symlink(link, target);
      } catch {
        await fs.promises.copyFile(resolved, target); // e.g. no symlink privilege on Windows hosts
        warn(`copied ${e.rel} instead of linking it (symlinks not available on this host)`);
      }
      continue;
    }
    await fs.promises.copyFile(e.abs, target);
    kept += e.stat.size;
  }
  return { kept, dropped };
}

/** True if `dir` holds an app produced by dropring-pack (so it may be replaced). */
function isOurOutput(dir, target) {
  const { base } = layoutFor(target, 'x');
  try {
    const m = JSON.parse(fs.readFileSync(join(dir, `${base}/${MANIFEST_FILE}`), 'utf8'));
    return m.generator === 'dropring-pack';
  } catch {
    return false;
  }
}

function launcherConfig({ target, runtime, layout, utf8Mode }) {
  const lines = [
    `# Generated by dropring-pack ${PACK_VERSION}. Read by the launcher; paths are relative to this file.`,
    'format=1',
    `python.lib=python/${layout.lib}`,
  ];
  // Windows: python3XY._pth isolates the interpreter and -I ignores PYTHON* variables.
  // POSIX: the launcher scrubs PYTHON* variables and sets PYTHONHOME (ADR-0001).
  if (target.os !== 'windows') lines.push('python.home=python');
  lines.push('boot=pack/boot.py');
  const flags = target.os === 'windows' ? ['-I', '-B'] : ['-s', '-B'];
  if (utf8Mode) flags.push('-X', 'utf8');
  for (const f of flags) lines.push(`flag=${f}`);
  return lines.join('\n') + '\n';
}

/**
 * @param {object} o
 * @param {import('./targets').Target} o.target
 * @param {import('./runtime').RuntimeSpec} o.runtime
 * @param {string} o.runtimeRoot  extracted python/ folder in the cache
 * @param {{path: string, sha256: string, version: string, kind: string}} o.launcher
 * @param {Awaited<ReturnType<typeof import('./analyze').analyze>>} o.analysis
 * @param {{name: string, appId: string, version: string, windowed: boolean, utf8Mode: boolean,
 *          company?: string, copyright?: string, description?: string, dpiAware?: boolean}} o.app
 * @param {{ico: Buffer|null, icns: Buffer|null, sha256: string}|null} [o.icon]  prepared icon files
 * @param {{from: string, to: string}[]} [o.includes]  extra data files (to = path inside app/)
 * @param {string} [o.signCmd]    Windows: command template that signs the executable
 * @param {string|null} [o.sitePackages]  verified third-party packages to copy into the app
 * @param {boolean} [o.keepTkinter]       bundle Tcl/Tk (app or a dependency uses tkinter)
 * @param {Record<string, string>} [o.appEnv]  runtime defaults (os.environ.setdefault)
 * @param {{source: string|null, distributions: object[], hooks: string[]}} [o.dependencies]
 * @param {boolean} [o.zip]       also write <name>-<version>-<target>.zip next to the app
 * @param {string} o.destDir      folder that receives the app
 * @param {'adhoc'|'none'} o.macSign
 * @param {(e: object) => void} o.emit
 * @param {AbortSignal} [o.signal]
 * @param {NodeJS.ProcessEnv} [o.env]
 */
async function assembleOnedir(o) {
  const { target, runtime, app, analysis, emit, signal } = o;
  const tag = { target: target.id };
  const warn = (message) => emit({ type: 'warning', ...tag, message });
  const fileName = sanitizeFileName(app.name);
  const layout = layoutFor(target, fileName);
  const files = runtimeLayout(runtime, target.os);
  const finalPath = path.join(o.destDir, layout.bundleName);
  if (fs.existsSync(finalPath) && !isOurOutput(finalPath, target)) {
    throw new Error(`${finalPath} already exists and was not created by dropring-pack; choose another --out or --name`);
  }
  await fs.promises.mkdir(o.destDir, { recursive: true });
  // Staging folder on the same volume; the bundle keeps its final name inside it (codesign
  // and Finder recognise `.app` bundles by name).
  const staging = path.join(o.destDir, `.dropring-pack-${crypto.randomBytes(6).toString('hex')}`);
  const stage = path.join(staging, layout.bundleName);
  const base = join(stage, layout.base);
  await fs.promises.mkdir(stage, { recursive: true });

  try {
    // 1. Runtime
    emit({ type: 'stage', stage: 'assemble', ...tag, message: `copying Python ${runtime.version} runtime` });
    const filter = runtimeFilter({ os: target.os, minor: runtime.minor, keepTkinter: o.keepTkinter ?? analysis.usesTkinter });
    const copied = await copyRuntime(o.runtimeRoot, join(base, 'python'), filter, warn);
    for (const [reason, bytes] of copied.dropped) emit({ type: 'log', level: 'debug', ...tag, message: `stripped ${(bytes / 1048576).toFixed(1)} MB: ${reason}` });
    if (!fs.existsSync(join(base, `python/${files.lib}`))) throw new Error(`the runtime has no ${files.lib}; its layout changed (python-build-standalone ${runtime.release})`);
    if (files.pth) await fs.promises.writeFile(join(base, `python/${files.pth}`), `# dropring-pack: module search path of the embedded interpreter (implies isolated mode)\nLib\nDLLs\nimport site\n`);
    throwIfAborted(signal);

    // 2. Application code and --include data files
    const includes = o.includes || [];
    emit({ type: 'stage', stage: 'assemble', ...tag, message: `copying ${analysis.files.length} application file(s)${includes.length ? ` and ${includes.length} included file(s)` : ''}` });
    const copies = new Map(analysis.files.map((rel) => [rel, join(analysis.root, rel)]));
    for (const inc of includes) copies.set(inc.to, inc.from); // an explicit include wins over a scanned file
    for (const [rel, from] of copies) {
      const dest = join(base, `app/${rel}`);
      await fs.promises.mkdir(path.dirname(dest), { recursive: true });
      await fs.promises.copyFile(from, dest);
    }
    if (o.sitePackages) {
      const dists = (o.dependencies && o.dependencies.distributions) || [];
      emit({ type: 'stage', stage: 'assemble', ...tag, message: `copying ${dists.length} third-party distribution(s)` });
      for (const e of await walk(o.sitePackages)) {
        if (e.type === 'dir') continue;
        const dest = join(base, `site-packages/${e.rel}`);
        await fs.promises.mkdir(path.dirname(dest), { recursive: true });
        if (e.type === 'symlink') await fs.promises.symlink(await fs.promises.readlink(e.abs), dest);
        else await fs.promises.copyFile(e.abs, dest);
      }
    }

    // 3. Bootstrap, helper module, app info, launcher config
    await fs.promises.mkdir(join(base, 'pack'), { recursive: true });
    for (const f of ['boot.py', 'dropring_pack_runtime.py']) await fs.promises.copyFile(path.join(BOOT_DIR, f), join(base, `pack/${f}`));
    const appEnv = o.appEnv || {};
    const appInfo = { format: 1, name: app.name, appId: app.appId, version: app.version, entry: `app/${analysis.entry}`, mode: 'onedir', subsystem: app.windowed ? 'windowed' : 'console', packVersion: PACK_VERSION };
    if (Object.keys(appEnv).length) appInfo.env = appEnv;
    await fs.promises.writeFile(join(base, 'pack/app.json'), JSON.stringify(appInfo, null, 2) + '\n');
    await fs.promises.writeFile(join(base, CONFIG_FILE), launcherConfig({ target, runtime, layout: files, utf8Mode: app.utf8Mode }));

    // 4. Launcher
    const exePath = join(stage, layout.executable);
    await fs.promises.mkdir(path.dirname(exePath), { recursive: true });
    await fs.promises.copyFile(o.launcher.path, exePath);

    // 5. Brand: icon, version info, manifest (Windows) / Info.plist and .icns (macOS)
    if (target.os === 'macos') {
      emit({ type: 'stage', stage: 'brand', ...tag, message: `writing Info.plist${o.icon ? ' and AppIcon.icns' : ''}` });
      const libMin = await macos.machoMinOsOfFile(join(base, `python/${files.lib}`));
      const exeMin = await macos.machoMinOsOfFile(exePath);
      const minOs = [libMin, exeMin, target.arch === 'arm64' ? '11.0' : '10.13'].filter(Boolean).sort(macos.compareVersions).pop();
      const extra = {};
      if (o.icon) {
        await fs.promises.writeFile(join(base, 'AppIcon.icns'), o.icon.icns);
        extra.CFBundleIconFile = 'AppIcon';
      }
      if (app.copyright) extra.NSHumanReadableCopyright = app.copyright;
      await fs.promises.writeFile(join(stage, 'Contents/Info.plist'), macos.infoPlist({ name: app.name, executable: path.posix.basename(layout.executable), appId: app.appId, version: app.version, minOs, extra }));
      await fs.promises.writeFile(join(stage, 'Contents/PkgInfo'), 'APPL????');
    } else {
      emit({ type: 'stage', stage: 'brand', ...tag, message: `version info${o.icon ? ', icon' : ''}${app.dpiAware ? ', DPI-aware manifest' : ''}` });
      await require('./windows').brandExe(exePath, {
        name: app.name, version: app.version, exeName: path.basename(layout.executable), company: app.company,
        copyright: app.copyright, description: app.description, ico: o.icon ? o.icon.ico : null, dpiAware: app.dpiAware,
      });
    }

    // 6. Deterministic permissions: launcher and native libraries executable, the rest read-only data.
    for (const e of await walk(stage)) {
      if (e.type === 'symlink') continue;
      await fs.promises.chmod(e.abs, modeFor(e.rel, e.type, layout.executable));
    }

    // 7. Manifest inside the app (provenance + every file's hash). The main executable is
    // listed by the launcher asset hash, because signing rewrites it.
    const manifest = {
      generator: 'dropring-pack',
      generatorVersion: PACK_VERSION,
      format: 1,
      engine: 'dropring-pack',
      app: { name: app.name, appId: app.appId, version: app.version, mode: 'onedir', subsystem: appInfo.subsystem, entry: appInfo.entry, executable: layout.executable },
      target: { id: target.id, os: target.os, arch: target.arch, triple: target.triple },
      python: { version: runtime.version, release: runtime.release, source: 'python-build-standalone', flavor: 'install_only_stripped', archiveSha256: runtime.sha256 },
      launcher: { version: o.launcher.version, kind: o.launcher.kind, sha256: o.launcher.sha256 },
      branding: { icon: o.icon ? o.icon.sha256 : null, company: app.company || null, copyright: app.copyright || null, dpiAware: !!app.dpiAware },
      analysis: { mode: analysis.mode, analyzer: analysis.analyzer, analyzerPython: analysis.analyzerPython, imports: analysis.imports, gui: analysis.gui, usesTkinter: analysis.usesTkinter },
      includes: includes.map((i) => i.to),
      dependencies: o.dependencies ? { source: o.dependencies.source, hooks: o.dependencies.hooks, distributions: o.dependencies.distributions.map(({ name, version, tag, license, files }) => ({ name, version, tag, license, files })) } : null,
      env: Object.keys(appEnv).sort(), // names only: values are not repeated in the manifest
      files: [],
      totals: null,
    };
    manifest.files = await hashTree(stage, { skip: (rel) => rel === layout.executable });
    manifest.totals = summarize(manifest.files);
    await fs.promises.writeFile(join(base, MANIFEST_FILE), JSON.stringify(manifest, null, 2) + '\n');
    throwIfAborted(signal);

    // 8. Sign
    if (target.os === 'macos') {
      if (o.macSign === 'none') emit({ type: 'stage', stage: 'sign', ...tag, message: 'skipped (--mac-sign none)' });
      else if (process.platform === 'darwin') {
        emit({ type: 'stage', stage: 'sign', ...tag, message: 'ad-hoc signing with codesign' });
        await macos.codesignAdhoc(stage);
      } else {
        emit({ type: 'stage', stage: 'sign', ...tag, message: 'not sealed on this host' });
        warn('the .app bundle is not sealed on this host (rcodesign support arrives in M3); its Mach-O files keep their original ad-hoc signatures, which is enough to run on Apple Silicon');
      }
    } else if (o.signCmd) {
      emit({ type: 'stage', stage: 'sign', ...tag, message: `signing ${path.basename(exePath)} with --sign-cmd (command not shown)` });
      await require('./sign').signFile(o.signCmd, exePath, { signal });
    } else {
      emit({ type: 'stage', stage: 'sign', ...tag, message: 'unsigned (pass --sign-cmd to sign with your certificate)' });
    }

    // 9. Verify the structure the launcher relies on.
    emit({ type: 'stage', stage: 'verify', ...tag, message: 'checking layout' });
    for (const rel of [layout.executable, `${layout.base}/${CONFIG_FILE}`, `${layout.base}/python/${files.lib}`, `${layout.base}/pack/boot.py`, `${layout.base}/${appInfo.entry}`]) {
      if (!fs.existsSync(join(stage, rel))) throw new Error(`verification failed: ${rel} is missing`);
    }

    // 10. Fixed timestamps (after signing, which rewrites files), then move into place.
    await setTreeTimes(stage, reproducibleDate(o.env));
    if (fs.existsSync(finalPath)) await fs.promises.rm(finalPath, { recursive: true, force: true });
    await fs.promises.rename(stage, finalPath);
  } finally {
    await fs.promises.rm(staging, { recursive: true, force: true });
  }

  // 11. Manifest next to the app with the final hashes of every file (DropRing shows this).
  const finalFiles = await hashTree(finalPath);
  const outer = { generator: 'dropring-pack', generatorVersion: PACK_VERSION, format: 1, artifact: layout.bundleName, target: target.id, executable: layout.executable, files: finalFiles, totals: summarize(finalFiles) };
  const manifestPath = `${finalPath}.manifest.json`;
  await fs.promises.writeFile(manifestPath, JSON.stringify(outer, null, 2) + '\n');
  let zipPath = null;
  if (o.zip) {
    zipPath = path.join(o.destDir, `${fileName}-${app.version}-${target.id}.zip`);
    emit({ type: 'stage', stage: 'zip', ...tag, message: path.basename(zipPath) });
    await zipDirectory(finalPath, zipPath, { date: reproducibleDate(o.env), modeOf: (rel, type) => modeFor(rel, type, layout.executable) });
  }
  return { target: target.id, path: finalPath, executable: join(finalPath, layout.executable), manifestPath, zipPath, sizeBytes: outer.totals.bytes, fileCount: outer.totals.count };
}

module.exports = { assembleOnedir, launcherConfig, layoutFor, modeFor, asciiExecutableName, MANIFEST_FILE, CONFIG_FILE };
